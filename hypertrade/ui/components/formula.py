import streamlit as st


def formula_help():
    with st.expander('Как выбираются кандидаты: цели, ограничения и shortlist'):
        st.markdown('''**Текущий default — качество сигналов**, четыре независимые Pareto-цели:
увеличить `sum_trade_returns_pct` (сумма доходностей сделок, процентные пункты),
уменьшить `proxy_drawdown_usd` (просадка последовательной normalized-кривой в USD),
увеличить `profit_factor`, уменьшить `avg_hold_minutes` (среднее удержание, минуты).

**PF** = сумма положительных доходностей сделок / модуль суммы отрицательных.
Это исследовательский PF, а не портфельный. Без убытков PF **не определён**;
при включении в цели/ограничения такой trial получает PRUNED.

**Жёсткие ограничения default:** `trades >= 20`, `profit_factor >= 1.05`.
В редакторе можно менять метрику, минимум/максимум и направление каждой цели:
`maximize` — увеличивать, `minimize` — уменьшать. Нарушение ограничения исключает trial.

**Pareto без weighted-score:** кандидат недоминируем, если другой допустимый
кандидат не лучше или равен по всем целям и строго лучше хотя бы по одной.
После Pareto вторичный shortlist по умолчанию сортируется по
`utopia_distance = sqrt(sum(normalized_deviation²))`.
Отклонения от лучшего значения нормализуются по диапазону Pareto каждой цели;
веса равны в нормализованном пространстве. Это **не основная оптимизация**.
Другая shortlist policy меняет только порядок предпочтения среди Pareto.

Default **не оптимизирует `portfolio_return_pct`**, хотя показывает её.
Доходность капитала `portfolio_return_pct` и просадка капитала
`portfolio_max_drawdown_pct` доступны как отдельные цели и в необязательных шаблонах.
Ограничения остаются редактируемыми; портфельные шаблоны также используют исследовательский PF.
Это **профиль поиска**, а не новая формула доходности.

NSGA-II сохраняется. Установленная версия Optuna поддерживает одну цель с этим sampler;
одномерный Pareto означает лучшее допустимое значение выбранной цели.
Улучшение кандидата может быть связано с SL/TP, задержкой и временем удержания,
а не только с индикаторами.''')
