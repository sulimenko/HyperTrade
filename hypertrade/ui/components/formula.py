import streamlit as st


def formula_help():
    with st.expander('Как выбираются кандидаты: цели, ограничения и порядок выбора'):
        st.markdown('''**По умолчанию — качество сигналов**, четыре независимые цели Парето:
увеличить сумму доходностей сделок (процентные пункты), уменьшить просадку
по порядку сделок (нормированные USD), увеличить фактор прибыли PF,
уменьшить среднее удержание (минуты).

**PF** — сумма положительных доходностей / модуль суммы отрицательных.
Это исследовательский PF. Без убытков он **не определён**;
если он включён в цели или ограничения, испытание отклоняется.

**Исходные жёсткие ограничения:** число исследовательских сделок ≥ 20,
PF ≥ 1,05. Цели, направления и ограничения можно изменить в расширенных
настройках. Нарушение порога исключает испытание.

**Парето:** кандидат недоминируем, если нет другого допустимого кандидата,
который не хуже по всем целям и строго лучше хотя бы по одной.
Взвешенной суммы целей нет. После оптимизации список по умолчанию
упорядочивается по расстоянию до идеальной точки:
квадратный корень суммы квадратов отклонений от лучших значений,
нормированных по диапазону Парето для каждой цели. Веса равны.
Порядок выбора влияет на предпочтение среди уже найденных кандидатов.

Исходный профиль **не оптимизирует доходность портфеля**, хотя показывает её.
Есть шаблоны одной портфельной цели и баланса доходности, просадки и PF.
Они сохраняют редактируемые ограничения и исследовательский PF.
Одна цель поддерживается тем же Optuna NSGA-II; её граница Парето —
лучшее допустимое значение.

Кандидаты меняют SL/TP, задержку и срок удержания, поэтому сравнение с исходной
стратегией не измеряет чистый эффект индикаторов. Историческая модель
экспериментальна и не доказывает будущую доходность.''')
