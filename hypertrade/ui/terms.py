def label(key):
    if key in LABELS:
        return LABELS[key]
    if key.endswith('_use') and key[:-4] in FILTERS:
        return FILTERS[key[:-4]][0]
    for suffix, word in [('_min', 'минимум'), ('_max', 'максимум'), ('_step', 'шаг')]:
        if key.endswith(suffix) and key[:-len(suffix)] in LABELS:
            return f'{label(key[:-len(suffix)])} · {word}'
    return key


def metric_help(key):
    return METRICS.get(key, (key, 'Сохранённое значение исторического исследования; расчёты при отображении не меняются.'))[1]


def value_label(value):
    if not isinstance(value, str):
        return value
    if value in VALUES:
        return VALUES[value]
    if value in LABELS:
        return label(value)
    if re.fullmatch(r'[Tt]rial \d+', value):
        return 'Испытание №' + value.split()[-1]
    if value.startswith(('undefined:', 'missing:')):
        prefix, metric = value.split(':', 1)
        return ('Не определено: ' if prefix == 'undefined' else 'Нет значения: ') + label(metric)
    if '<min' in value or '>max' in value:
        metric, bound = value.split('<min')[0].split('>max')[0], ('ниже минимума' if '<min' in value else 'выше максимума')
        return f'{label(metric)}: {bound}'
    if value.startswith('rejected_missing_'):
        return 'Нет значения индикатора: ' + value.removeprefix('rejected_missing_')
    return value


def display_frame(frame):
    result = frame.copy(deep=True)
    for col in result:
        if col in {'state', 'status', 'metric', 'reason', 'exit_reason', 'candidate', 'source', 'Статус', 'Причина', 'Параметр', 'stage', 'event_phase', 'ranking_mode'} or col.endswith(('_sign', '_mode')):
            result[col] = result[col].map(value_label)
        elif col == 'direction':
            result[col] = result[col].map(lambda v: {1: 'Покупка', -1: 'Продажа'}.get(v, v))
    return result


def table(frame, **kwargs):
    """Keep row order and numeric ids for linked selection; show raw extras on demand."""
    core = [c for c in frame if label(c) != c or re.search('[А-Яа-я]', c)]
    technical = [c for c in frame if c not in core]
    shown = frame[core] if core else frame
    result = st.dataframe(display_frame(shown), column_config={
        c: st.column_config.Column(label(c), help=metric_help(c)) for c in shown
    }, **kwargs)
    if technical:
        with st.expander('Технические столбцы · исходные имена'):
            st.dataframe(frame, hide_index=True, width='stretch')
    return result


